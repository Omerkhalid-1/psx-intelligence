"""Static export of the public website for hosts that only serve files (GitHub Pages).

Every page is rendered through the real application (same templates, same engine) under the deployment
base path, e.g. "/psx-intelligence" for https://<user>.github.io/psx-intelligence/. The JSON API the pages
call is replaced by pre-built files under <base>/data/ (see core.js `staticJSON`):

    data/engine/<SYMBOL>.json   engine readings + 750-session series      (= /api/v1/engine/<s>?series=true)
    data/diagnostics.json       engine self-checks on the exported data   (= /api/v1/engine/diagnostics)
    data/symbols.json           PSX listing for autocomplete              (= /api/v1/symbols/search, filtered in JS)
    data/news/<SYMBOL>.json     headlines for each tracked symbol          (= /api/v1/news/search?symbol=<s>)

The export fails (and nothing is published) if any page errors or any internal link would 404.
"""

from __future__ import annotations

import json
import logging
import re
import shutil
import time
from datetime import datetime
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

from flask import Flask

from app.utils.time import PSX_TZ, utcnow

log = logging.getLogger(__name__)

MARKER = ".psx-site-export"
BASE_PATTERN = re.compile(r"(/[A-Za-z0-9._-]+)*")
_LINK = re.compile(r'\b(href|src|action)="([^"]*)"')


class ExportError(RuntimeError):
    pass


def normalize_base(base: str) -> str:
    base = "/" + base.strip().strip("/") if base.strip().strip("/") else ""
    if not BASE_PATTERN.fullmatch(base) or any(seg.strip(".") == "" for seg in base.split("/")[1:]):
        raise ExportError(f"invalid base path {base!r}: use letters, digits, '.', '_' or '-' segments "
                          "(not '.' or '..')")
    return base


def _prepare_out(out: Path) -> None:
    """Never delete a directory this exporter did not create."""
    if out.exists():
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise ExportError(f"{out} exists and is not a previous site export; refusing to overwrite it")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by `flask --app wsgi site export`; safe to delete\n")


def _write(out: Path, rel: str, content: str | bytes) -> None:
    path = out / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode() if isinstance(content, str) else content)


def _slash_pages(html: str, base: str, pages: set[str]) -> str:
    """Exported pages are directories (<page>/index.html): link to "<page>/" to avoid a redirect."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        path, sep, rest = url.partition("?")
        frag = ""
        if not sep and "#" in path:
            path, _, frag = path.partition("#")
            frag = "#" + frag
        if path in pages:
            return f'{attr}="{path}/{sep}{rest}{frag}"'
        return m.group(0)
    return _LINK.sub(fix, html)


def _check_links(out: Path, base: str) -> list[str]:
    """Every internal href/src/action in the export must resolve to an exported file."""
    broken = []
    prefix = (base or "") + "/"
    for page in out.rglob("*.html"):
        for _, url in _LINK.findall(page.read_text()):
            if not url.startswith(prefix) or url.startswith("//"):
                continue
            path = urlsplit(url).path[len(base):] if base else urlsplit(url).path
            target = out / path.lstrip("/")
            if path.endswith("/"):
                target = target / "index.html"
            if not target.exists():
                broken.append(f"{page.relative_to(out)} -> {url}")
    return sorted(set(broken))


def _latest_session() -> str | None:
    from sqlalchemy import func, select

    from app.extensions import db
    from app.models.market_data import DailyBar
    from app.services.research.prices import BENCHMARK

    d = db.session.scalar(select(func.max(DailyBar.session_date)).where(DailyBar.symbol == BENCHMARK,
                                                                       DailyBar.is_current))
    return d.isoformat() if d else None


def export_site(app: Flask, out: Path, base: str = "", *, with_news: bool = True,
                news_pause_seconds: float = 2.0) -> dict[str, Any]:
    base = normalize_base(base)
    config = app.config
    symbols = list(config["PSXDATA_SYMBOLS"])
    started = time.perf_counter()
    report: dict[str, Any] = {"base": base, "pages": 0, "data_files": 0, "news": {}, "warnings": []}

    with app.app_context():
        latest = _latest_session()
        if latest is None:
            raise ExportError("no market data stored: ingest daily bars before exporting")
        built = utcnow()
        config["SITE_STATIC_EXPORT"] = True
        config["SITE_BUILD_INFO"] = {"latest_session": latest, "built_at": built.isoformat(),
                                     "built_at_pkt": built.astimezone(PSX_TZ).strftime("%Y-%m-%d %H:%M")}
        _prepare_out(out)
        client = app.test_client()
        env = {"SCRIPT_NAME": base}

        def get(path: str, expect: int = 200):
            resp = client.get(path, environ_overrides=env)
            if resp.status_code != expect:
                raise ExportError(f"GET {path} returned {resp.status_code}, expected {expect}")
            return resp

        routes = {"/": "index.html", "/learn": "learn/index.html", "/news": "news/index.html",
                  "/engine": "engine/index.html"}
        routes |= {f"/stock/{s}": f"stock/{s}/index.html" for s in symbols}
        page_urls = {base + r for r in routes if r != "/"}
        for route, rel in routes.items():
            html = get(route).get_data(as_text=True)
            _write(out, rel, _slash_pages(html, base, page_urls))
            report["pages"] += 1
        _write(out, "404.html", _slash_pages(get("/__not-found__", expect=404).get_data(as_text=True), base,
                                             page_urls))
        _write(out, "robots.txt", "User-agent: *\nAllow: /\n")

        for s in symbols:
            body = get(f"/api/v1/engine/{s}?series=true&limit=750").get_data()
            _write(out, f"data/engine/{s}.json", body)
            report["data_files"] += 1
            issues = json.loads(body)["data"].get("data_issues") or []
            if issues:
                report["warnings"].append(f"{s}: unexplained price gap(s) on {', '.join(i['date'] for i in issues)} "
                                          "(unrecorded corporate action?) — shown as a warning on its page")
        _write(out, "data/diagnostics.json", get("/api/v1/engine/diagnostics").get_data())
        diag = json.loads((out / "data/diagnostics.json").read_text())["data"]
        if diag["summary"]["fail"]:
            raise ExportError(f"engine self-checks failed on the export data: {diag['summary']}")

        from app.services.news import search

        listing = search.load_listing(config)
        tracked = set(symbols)
        rows = [{"symbol": k, "name": v, "tracked": k in tracked} for k, v in sorted(listing.items())]
        _write(out, "data/symbols.json", json.dumps({"data": rows}, separators=(",", ":")))
        report["data_files"] += 2

        if with_news:
            for i, s in enumerate(symbols):
                if i:
                    time.sleep(news_pause_seconds)  # polite pacing towards Google News
                try:
                    result = search.search(config, s, limit=40, use_cache=False)  # a snapshot must be fresh
                except (search.SearchUnavailable, search.UnknownSymbol) as exc:
                    report["news"][s] = f"skipped: {exc}"
                    report["warnings"].append(f"no news file for {s}: {exc}")
                    continue
                payload = {"data": result, "warnings": [result["warning"]] if result.get("warning") else []}
                _write(out, f"data/news/{s}.json", json.dumps(payload, separators=(",", ":"), default=str))
                report["news"][s] = result["counts"]["shown"]
                report["data_files"] += 1

        shutil.copytree(app.static_folder, out / "static")
        _write(out, ".nojekyll", "")  # serve every file as-is (no Jekyll processing)
        info = {**config["SITE_BUILD_INFO"], "symbols": symbols, "base": base,
                "engine_version": diag["engine_version"], "diagnostics": diag["summary"]}
        _write(out, "build-info.json", json.dumps(info, indent=1))

        broken = _check_links(out, base)
        if broken:
            raise ExportError(f"{len(broken)} broken internal link(s), e.g. {broken[:5]}")
    report.update(latest_session=latest, seconds=round(time.perf_counter() - started, 1),
                  built_at=datetime.fromisoformat(info["built_at"]).isoformat())
    log.info("static site exported", extra={"event_type": "site_exported", "details": report})
    return report
